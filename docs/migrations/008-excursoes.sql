CREATE TABLE excursoes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organizador_id bigint NOT NULL REFERENCES usuarios(id), titulo varchar(120) NOT NULL,
 destino_nome varchar(255) NOT NULL, destino_latitude double precision NOT NULL,
 destino_longitude double precision NOT NULL, origem_nome varchar(255),
 origem_latitude double precision, origem_longitude double precision,
 partida_em timestamptz NOT NULL, retorno_em timestamptz, criada_em timestamptz NOT NULL,
 capacidade integer NOT NULL CHECK(capacidade>0),
 estado varchar(30) NOT NULL DEFAULT 'RASCUNHO' CHECK(estado IN('RASCUNHO','PUBLICADA','CANCELADA','CONCLUIDA')),
 versao bigint NOT NULL DEFAULT 0,
 CHECK(destino_latitude BETWEEN -90 AND 90 AND destino_longitude BETWEEN -180 AND 180 AND NOT(destino_latitude=0 AND destino_longitude=0)),
 CHECK((origem_nome IS NULL AND origem_latitude IS NULL AND origem_longitude IS NULL) OR
 (origem_nome IS NOT NULL AND origem_latitude IS NOT NULL AND origem_longitude IS NOT NULL AND origem_latitude BETWEEN -90 AND 90 AND origem_longitude BETWEEN -180 AND 180 AND NOT(origem_latitude=0 AND origem_longitude=0))),
 CHECK(retorno_em IS NULL OR retorno_em>partida_em)
);
CREATE INDEX idx_excursoes_organizador ON excursoes(organizador_id,id DESC);
