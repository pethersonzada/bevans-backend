BEGIN;
CREATE TABLE credenciais_inscricao_excursao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 excursao_id bigint NOT NULL REFERENCES excursoes(id), token_hash varchar(64) NOT NULL UNIQUE,
 expira_em timestamptz NOT NULL
);
CREATE INDEX idx_credenciais_inscricao_excursao ON credenciais_inscricao_excursao(excursao_id,expira_em);
CREATE TABLE inscricoes_excursao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 excursao_id bigint NOT NULL REFERENCES excursoes(id),
 credencial_id bigint NOT NULL UNIQUE REFERENCES credenciais_inscricao_excursao(id),
 nome varchar(120) NOT NULL, contato varchar(150) NOT NULL, participante_hash varchar(64) NOT NULL,
 parada_id bigint REFERENCES paradas_excursao(id), nome_ponto varchar(120) NOT NULL,
 latitude double precision NOT NULL CHECK(latitude BETWEEN -90 AND 90),
 longitude double precision NOT NULL CHECK(longitude BETWEEN -180 AND 180),
 estado varchar(20) NOT NULL CHECK(estado IN('SOLICITADA','CONFIRMADA','CANCELADA','EXPIRADA')),
 reserva_valida_ate timestamptz NOT NULL, consentimento_em timestamptz NOT NULL, confirmada_em timestamptz,
 CHECK(latitude<>0 OR longitude<>0)
);
CREATE UNIQUE INDEX uq_inscricao_excursao_ativa ON inscricoes_excursao(excursao_id,participante_hash)
 WHERE estado IN('SOLICITADA','CONFIRMADA');
CREATE INDEX idx_inscricoes_excursao_ocupacao ON inscricoes_excursao(excursao_id,estado,reserva_valida_ate);
COMMIT;
