-- Incremental, sem publicação/backfill automático de turmas privadas.
-- Aplicar após 001 em PostgreSQL isolado antes de qualquer implantação.
BEGIN;
CREATE TABLE IF NOT EXISTS rotas_publicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turma_id BIGINT NOT NULL UNIQUE REFERENCES turmas(id),
    nome VARCHAR(120) NOT NULL, cidade VARCHAR(120) NOT NULL,
    categoria VARCHAR(255) NOT NULL CHECK (categoria IN ('ESCOLAR','UNIVERSITARIA','OUTROS')),
    modo VARCHAR(255) NOT NULL CHECK (modo IN ('FIXA','FLEXIVEL')),
    origem_nome VARCHAR(255) NOT NULL, origem_latitude DOUBLE PRECISION NOT NULL CHECK (origem_latitude BETWEEN -90 AND 90),
    origem_longitude DOUBLE PRECISION NOT NULL CHECK (origem_longitude BETWEEN -180 AND 180),
    destino_nome VARCHAR(255) NOT NULL, destino_latitude DOUBLE PRECISION NOT NULL CHECK (destino_latitude BETWEEN -90 AND 90),
    destino_longitude DOUBLE PRECISION NOT NULL CHECK (destino_longitude BETWEEN -180 AND 180),
    descricao VARCHAR(2000), regiao VARCHAR(255), campus VARCHAR(255), horario_ida TIME, horario_volta TIME,
    publicada BOOLEAN NOT NULL DEFAULT FALSE, ativa BOOLEAN NOT NULL DEFAULT TRUE, versao BIGINT NOT NULL DEFAULT 0,
    CHECK (origem_latitude <> 0 OR origem_longitude <> 0), CHECK (destino_latitude <> 0 OR destino_longitude <> 0)
);
CREATE TABLE IF NOT EXISTS rota_publica_dias (
    rota_id BIGINT NOT NULL REFERENCES rotas_publicas(id),
    dia VARCHAR(255) NOT NULL CHECK (dia IN ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
    PRIMARY KEY(rota_id,dia)
);
CREATE TABLE IF NOT EXISTS paradas_publicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_id BIGINT NOT NULL REFERENCES rotas_publicas(id),
    ordem INTEGER NOT NULL CHECK (ordem >= 0), nome VARCHAR(120) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    horario TIME, ativa BOOLEAN NOT NULL DEFAULT TRUE, CHECK (latitude <> 0 OR longitude <> 0)
);
CREATE INDEX IF NOT EXISTS idx_paradas_rota_ordem ON paradas_publicas(rota_id,ordem);
CREATE INDEX IF NOT EXISTS idx_rotas_publicadas_cidade ON rotas_publicas(cidade,categoria) WHERE publicada AND ativa;
COMMIT;
