-- Fixture do schema dos seis modelos de origin/main 1a24bb3.
-- Somente PostgreSQL de teste; nao e script de implantacao.
CREATE TABLE usuarios (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome varchar(255) NOT NULL, telefone varchar(255) NOT NULL UNIQUE,
 email varchar(255) NOT NULL UNIQUE, firebase_uid varchar(255), tipo varchar(255) NOT NULL,
 endereco_completo varchar(255), latitude double precision, longitude double precision
);
CREATE TABLE turmas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 motorista_id bigint REFERENCES usuarios(id), nome varchar(255), turno varchar(255),
 codigo_convite varchar(255), origem_nome varchar(255), origem_latitude double precision,
 origem_longitude double precision, destino_nome varchar(255), destino_latitude double precision,
 destino_longitude double precision, excluido boolean NOT NULL DEFAULT false
);
CREATE TABLE aluno_turma (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 turma_id bigint REFERENCES turmas(id), aluno_id bigint REFERENCES usuarios(id),
 status varchar(255), excluido boolean NOT NULL DEFAULT false
);
CREATE TABLE enderecos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id bigint REFERENCES usuarios(id), apelido varchar(255), rua varchar(255),
 numero varchar(255), bairro varchar(255), complemento varchar(255),
 latitude double precision, longitude double precision
);
CREATE TABLE viagem (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 turma_id bigint NOT NULL REFERENCES turmas(id), sentido varchar(255) NOT NULL,
 status varchar(255) NOT NULL, data_criacao timestamp(6), excluido boolean NOT NULL DEFAULT false
);
CREATE TABLE presencas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id bigint NOT NULL REFERENCES usuarios(id), turma_id bigint REFERENCES turmas(id),
 endereco_id bigint REFERENCES enderecos(id), endereco_ida_id bigint REFERENCES enderecos(id),
 endereco_volta_id bigint REFERENCES enderecos(id), viagem_id bigint REFERENCES viagem(id),
 data date NOT NULL, status varchar(255) NOT NULL
);
