BEGIN;
CREATE TABLE execucoes_excursao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 excursao_id bigint NOT NULL REFERENCES excursoes(id), sentido varchar(5) NOT NULL CHECK(sentido IN('IDA','VOLTA')),
 estado varchar(20) NOT NULL CHECK(estado IN('EM_ANDAMENTO','FINALIZADA','CANCELADA')),
 iniciada_em timestamptz NOT NULL, finalizada_em timestamptz,
 roteiro_json text NOT NULL, snapshot_versao integer NOT NULL DEFAULT 1 CHECK(snapshot_versao>0),
 versao bigint NOT NULL DEFAULT 0, UNIQUE(excursao_id,sentido)
);
CREATE UNIQUE INDEX uq_execucao_excursao_ativa ON execucoes_excursao(excursao_id) WHERE estado='EM_ANDAMENTO';
COMMIT;
