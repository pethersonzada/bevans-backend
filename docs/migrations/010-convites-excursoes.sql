CREATE TABLE convites_excursao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 excursao_id bigint NOT NULL REFERENCES excursoes(id), token_hash varchar(64) NOT NULL UNIQUE,
 criado_em timestamptz NOT NULL, expira_em timestamptz NOT NULL, revogado_em timestamptz,
 CHECK(expira_em>criado_em)
);
CREATE INDEX idx_convites_excursao ON convites_excursao(excursao_id,id);
