CREATE TABLE convites_responsavel (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,passageiro_id bigint NOT NULL REFERENCES usuarios(id),
 token_hash varchar(64) NOT NULL UNIQUE,expira_em timestamptz NOT NULL,consumido_em timestamptz,revogado_em timestamptz
);
CREATE INDEX idx_convites_responsavel_passageiro ON convites_responsavel(passageiro_id);
CREATE TABLE vinculos_responsavel (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,passageiro_id bigint NOT NULL REFERENCES usuarios(id),responsavel_id bigint NOT NULL REFERENCES usuarios(id),
 estado varchar(30) NOT NULL CHECK(estado IN('SOLICITADO','AGUARDANDO_VERIFICACAO','ATIVO','REVOGADO')),criado_em timestamptz NOT NULL,
 consentimento_passageiro_em timestamptz,consentimento_responsavel_em timestamptz,verificado_em timestamptz,revogado_em timestamptz,
 termo_passageiro varchar(40),termo_responsavel varchar(40),referencia_verificacao varchar(200),versao bigint NOT NULL DEFAULT 0,
 UNIQUE(passageiro_id,responsavel_id),CHECK(passageiro_id<>responsavel_id),
 CHECK(estado<>'ATIVO' OR(consentimento_passageiro_em IS NOT NULL AND consentimento_responsavel_em IS NOT NULL AND verificado_em IS NOT NULL AND referencia_verificacao IS NOT NULL AND termo_passageiro IS NOT NULL AND termo_responsavel IS NOT NULL AND termo_passageiro=termo_responsavel))
);
CREATE INDEX idx_vinculos_responsavel_responsavel ON vinculos_responsavel(responsavel_id,id);
CREATE TABLE eventos_responsabilidade (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,vinculo_id bigint NOT NULL REFERENCES vinculos_responsavel(id),autor_id bigint NOT NULL REFERENCES usuarios(id),
 acao varchar(40) NOT NULL,estado varchar(30) NOT NULL,criado_em timestamptz NOT NULL,versao_vinculo bigint NOT NULL,
 termo_versao varchar(40),referencia_verificacao varchar(200),UNIQUE(vinculo_id,versao_vinculo)
);
