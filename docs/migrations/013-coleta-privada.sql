BEGIN;
CREATE TABLE coletas_privadas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, turma_id bigint NOT NULL REFERENCES turmas(id),
 sentido varchar(5) NOT NULL CHECK(sentido IN('IDA','VOLTA')), modo varchar(255) NOT NULL CHECK(modo IN('PORTA_A_PORTA','PARADAS_DEFINIDAS')),
 revisao bigint NOT NULL DEFAULT 0, versao bigint NOT NULL DEFAULT 0, UNIQUE(turma_id,sentido)
);
CREATE TABLE paradas_privadas (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, coleta_id bigint NOT NULL REFERENCES coletas_privadas(id),
 nome varchar(120) NOT NULL, latitude double precision NOT NULL CHECK(latitude BETWEEN -90 AND 90),
 longitude double precision NOT NULL CHECK(longitude BETWEEN -180 AND 180), ordem integer NOT NULL CHECK(ordem>=0),
 horario time, ativa boolean NOT NULL DEFAULT true, CHECK(latitude<>0 OR longitude<>0)
);
CREATE INDEX idx_paradas_privadas_coleta ON paradas_privadas(coleta_id,ordem,id);
CREATE TABLE escolhas_parada_privada (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, coleta_id bigint NOT NULL REFERENCES coletas_privadas(id),
 aluno_id bigint NOT NULL REFERENCES usuarios(id), parada_id bigint NOT NULL REFERENCES paradas_privadas(id),
 ativa boolean NOT NULL DEFAULT true, UNIQUE(coleta_id,aluno_id)
);
CREATE INDEX idx_escolhas_parada_privada ON escolhas_parada_privada(coleta_id,ativa);
COMMIT;
