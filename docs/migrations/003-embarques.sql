-- Pedidos privados separados do catálogo; não copiar coordenadas para paradas.
BEGIN;
CREATE TABLE IF NOT EXISTS solicitacoes_embarque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rota_id BIGINT NOT NULL REFERENCES rotas_publicas(id),
    aluno_id BIGINT NOT NULL REFERENCES usuarios(id),
    vinculo_id BIGINT REFERENCES aluno_turma(id),
    parada_id BIGINT REFERENCES paradas_publicas(id),
    data_operacao DATE NOT NULL, sentido VARCHAR(5) NOT NULL CHECK (sentido IN ('IDA','VOLTA')),
    nome_ponto VARCHAR(120) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    observacao VARCHAR(500), status VARCHAR(20) NOT NULL CHECK (status IN ('PENDENTE','APROVADO','REJEITADO','CANCELADO')),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL, analisado_em TIMESTAMP WITH TIME ZONE, analisado_por BIGINT,
    versao BIGINT NOT NULL DEFAULT 0, CHECK (latitude <> 0 OR longitude <> 0)
);
CREATE INDEX IF NOT EXISTS idx_embarque_execucao ON solicitacoes_embarque(rota_id,data_operacao,sentido,status);
CREATE INDEX IF NOT EXISTS idx_embarque_titular ON solicitacoes_embarque(aluno_id,id DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_embarque_aberto ON solicitacoes_embarque(rota_id,aluno_id,data_operacao,sentido)
    WHERE status IN ('PENDENTE','APROVADO');
COMMIT;
