BEGIN;
CREATE TABLE operacoes_viagem (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tipo varchar(20) NOT NULL CHECK(tipo IN('VIAGEM','EXCURSAO')),
 referencia_id bigint NOT NULL, viagem_id bigint UNIQUE REFERENCES viagem(id),
 execucao_excursao_id bigint UNIQUE REFERENCES execucoes_excursao(id), motorista_id bigint NOT NULL REFERENCES usuarios(id),
 sentido varchar(5) NOT NULL CHECK(sentido IN('IDA','VOLTA')), versao bigint NOT NULL DEFAULT 0, UNIQUE(tipo,referencia_id),
 CHECK((tipo='VIAGEM' AND viagem_id=referencia_id AND viagem_id IS NOT NULL AND execucao_excursao_id IS NULL)
 OR(tipo='EXCURSAO' AND execucao_excursao_id=referencia_id AND execucao_excursao_id IS NOT NULL AND viagem_id IS NULL))
);
CREATE TABLE registros_operacionais (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, operacao_id bigint NOT NULL REFERENCES operacoes_viagem(id),
 aluno_id bigint REFERENCES usuarios(id), inscricao_id bigint REFERENCES inscricoes_excursao(id), nome varchar(255) NOT NULL,
 estado varchar(20) NOT NULL CHECK(estado IN('AGUARDANDO','EMBARCADO','NAO_EMBARCOU','DESEMBARCADO')),
 ordem integer NOT NULL CHECK(ordem>=0), parada_id bigint,
 latitude double precision NOT NULL CHECK(latitude BETWEEN -90 AND 90), longitude double precision NOT NULL CHECK(longitude BETWEEN -180 AND 180),
 autor varchar(80), origem varchar(20), atualizado_em timestamptz, versao bigint NOT NULL DEFAULT 0,
 UNIQUE(operacao_id,aluno_id),UNIQUE(operacao_id,inscricao_id),
 CHECK((aluno_id IS NOT NULL AND inscricao_id IS NULL) OR(aluno_id IS NULL AND inscricao_id IS NOT NULL))
);
CREATE INDEX idx_registros_operacionais_estado ON registros_operacionais(operacao_id,estado,ordem);
CREATE TABLE eventos_operacionais (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, registro_id bigint NOT NULL REFERENCES registros_operacionais(id),
 anterior varchar(20) NOT NULL, novo varchar(20) NOT NULL, autor varchar(80) NOT NULL, origem varchar(20) NOT NULL,
 criado_em timestamptz NOT NULL, correcao boolean NOT NULL, motivo varchar(500), versao_registro bigint NOT NULL,
 UNIQUE(registro_id,versao_registro)
);
COMMIT;
