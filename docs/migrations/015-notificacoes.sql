BEGIN;
CREATE TABLE notificacoes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, usuario_id bigint REFERENCES usuarios(id), inscricao_id bigint REFERENCES inscricoes_excursao(id),
 operacao_id bigint REFERENCES operacoes_viagem(id), registro_id bigint REFERENCES registros_operacionais(id),
 tipo varchar(60) NOT NULL, contexto_tipo varchar(40) NOT NULL, contexto_id bigint NOT NULL, chave varchar(250) NOT NULL UNIQUE,
 titulo varchar(120) NOT NULL, mensagem varchar(255) NOT NULL, criada_em timestamptz NOT NULL, lida_em timestamptz,
 CHECK((usuario_id IS NOT NULL AND inscricao_id IS NULL) OR(usuario_id IS NULL AND inscricao_id IS NOT NULL))
);
CREATE INDEX idx_notificacoes_usuario ON notificacoes(usuario_id,id DESC);
CREATE INDEX idx_notificacoes_inscricao ON notificacoes(inscricao_id,id DESC);
CREATE TABLE preferencias_notificacao(usuario_id bigint PRIMARY KEY REFERENCES usuarios(id),push_operacional boolean NOT NULL DEFAULT true,push_informativo boolean NOT NULL DEFAULT true);
CREATE TABLE dispositivos_notificacao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,usuario_id bigint NOT NULL REFERENCES usuarios(id),instalacao_id varchar(128) NOT NULL UNIQUE,
 token varchar(4096) NOT NULL,token_hash varchar(64) NOT NULL UNIQUE,ativo boolean NOT NULL DEFAULT true,atualizado_em timestamptz NOT NULL
);
CREATE INDEX idx_dispositivos_usuario ON dispositivos_notificacao(usuario_id,ativo);
CREATE TABLE outbox_notificacao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,chave varchar(200) NOT NULL UNIQUE,tipo varchar(60) NOT NULL,
 operacao_id bigint REFERENCES operacoes_viagem(id),registro_id bigint REFERENCES registros_operacionais(id),usuario_id bigint REFERENCES usuarios(id),inscricao_id bigint REFERENCES inscricoes_excursao(id),
 origem varchar(20),contexto_tipo varchar(40),contexto_id bigint,estado varchar(20) NOT NULL DEFAULT 'PENDENTE',tentativas integer NOT NULL DEFAULT 0,
 criada_em timestamptz NOT NULL,proxima_tentativa timestamptz NOT NULL
);
CREATE INDEX idx_outbox_notificacao_pendente ON outbox_notificacao(estado,proxima_tentativa,id);
CREATE TABLE entregas_push (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,notificacao_id bigint NOT NULL REFERENCES notificacoes(id),dispositivo_id bigint NOT NULL REFERENCES dispositivos_notificacao(id),
 estado varchar(20) NOT NULL DEFAULT 'PENDENTE',tentativas integer NOT NULL DEFAULT 0,proxima_tentativa timestamptz NOT NULL,resultado varchar(40),UNIQUE(notificacao_id,dispositivo_id)
);
CREATE INDEX idx_entregas_push_pendentes ON entregas_push(estado,proxima_tentativa,id);
COMMIT;
-- Feed/outbox preservados em rollback. Tokens de dispositivos não devem ir para logs/respostas.
