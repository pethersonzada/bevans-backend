BEGIN;
CREATE TABLE IF NOT EXISTS rotas_favoritas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id), rota_id BIGINT NOT NULL REFERENCES rotas_publicas(id),
    ativo BOOLEAN NOT NULL DEFAULT TRUE, CONSTRAINT uq_favorito_usuario_rota UNIQUE(usuario_id,rota_id)
);
CREATE INDEX IF NOT EXISTS idx_favoritos_titular ON rotas_favoritas(usuario_id,ativo,rota_id);
