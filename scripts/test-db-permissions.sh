#!/usr/bin/env bash
set -Eeuo pipefail

cd "$(dirname "$0")/.."

SCHEMA="bevans_perm_probe_$$"
ROLE="bevans_perm_role_$$"
DB="${PGDATABASE:-bevans_homolog}"
LOCAL="${BEVANS_PSQL_SUDO:-0}"

psqlcmd() {
    if [ "$LOCAL" = "1" ]; then
        sudo -u postgres psql \
            -X -v ON_ERROR_STOP=1 -d "$DB" "$@"
    else
        psql -X -v ON_ERROR_STOP=1 -d "$DB" "$@"
    fi
}

cleanup() {
    set +e
    psqlcmd -q -c "
        DROP SCHEMA IF EXISTS \"$SCHEMA\" CASCADE;
        DROP OWNED BY \"$ROLE\";
        DROP ROLE IF EXISTS \"$ROLE\";
    " >/dev/null 2>&1
}
trap cleanup EXIT

echo "=== PREPARANDO TESTE ISOLADO ==="

psqlcmd -q -c "
    CREATE ROLE \"$ROLE\" NOLOGIN;
    CREATE SCHEMA \"$SCHEMA\";
    CREATE TABLE \"$SCHEMA\".registro (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        descricao text NOT NULL
    );
    CREATE SEQUENCE \"$SCHEMA\".contador;
"

echo "=== ANTES DA CORREÇÃO ==="

ANTES=$(psqlcmd -At -c "
    SELECT has_table_privilege(
        '$ROLE',
        '$SCHEMA.registro',
        'SELECT'
    );
")

if [ "$ANTES" != "f" ]; then
    echo "FALHOU: role já possui acesso inesperado."
    exit 1
fi

echo "PASSOU: role sem privilégios não acessa a tabela."

echo "=== APLICANDO CORREÇÃO ==="

for tentativa in 1 2; do
    psqlcmd -q \
        -v app_role="$ROLE" \
        -v owner_role=postgres \
        -v schema_name="$SCHEMA" \
        < scripts/sql/grant-app-permissions.sql

    echo "PASSOU: aplicação $tentativa."
done

echo "=== TESTANDO PRIVILÉGIOS ==="

psqlcmd -q -c "
    SET ROLE \"$ROLE\";

    INSERT INTO \"$SCHEMA\".registro(descricao)
    VALUES ('teste');

    SELECT * FROM \"$SCHEMA\".registro;

    UPDATE \"$SCHEMA\".registro
    SET descricao='alterado';

    DELETE FROM \"$SCHEMA\".registro;

    SELECT nextval('$SCHEMA.contador');

    RESET ROLE;
" >/dev/null

echo "PASSOU: SELECT, INSERT, UPDATE, DELETE e sequência."

echo "=== TESTANDO MIGRAÇÕES FUTURAS ==="

psqlcmd -q -c "
    CREATE TABLE \"$SCHEMA\".registro_futuro (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        descricao text NOT NULL
    );

    CREATE SEQUENCE \"$SCHEMA\".sequencia_futura;
"

psqlcmd -q -c "
    SET ROLE \"$ROLE\";

    INSERT INTO \"$SCHEMA\".registro_futuro(descricao)
    VALUES ('migração futura');

    SELECT * FROM \"$SCHEMA\".registro_futuro;

    UPDATE \"$SCHEMA\".registro_futuro
    SET descricao='atualizado';

    DELETE FROM \"$SCHEMA\".registro_futuro;

    SELECT nextval('$SCHEMA.sequencia_futura');

    RESET ROLE;
" >/dev/null

echo "PASSOU: tabelas e sequências futuras."

echo "=== TESTE CONCLUÍDO ==="
echo "Todos os testes de privilégios passaram."
echo "Os objetos temporários serão excluídos."
